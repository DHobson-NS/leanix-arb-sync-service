package com.nscorp.entarch.leanix.arb.entity;

import io.quarkus.hibernate.orm.panache.PanacheEntityBase;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;

import java.time.LocalDateTime;
import java.util.UUID;

/** Audit record of an ArchitectureReview fact sheet created in LeanIX for an Initiative. */
@Entity
@Table(name = "architecture_review")
public class ArchitectureReview extends PanacheEntityBase {

    /** Primary key of the record, generated by the database. */
    @Id
    @GeneratedValue(strategy = GenerationType.UUID)
    @Column(name = "ARB_ID", updatable = false, nullable = false)
    public UUID arbId;

    /** Name given to the new ArchitectureReview fact sheet, limited to 36 characters. */
    @Column(name = "arb_name", length = 36, nullable = false)
    public String arbName;

    /** When the record was created. */
    @Column(name = "created_ts", nullable = false)
    public LocalDateTime createdTs = LocalDateTime.now();

    /** Name of the process that created the record. */
    @Column(name = "created_by", length = 24, nullable = false)
    public String createdBy = "leanIX_arb_upd";

    /** LeanIX Initiative fact sheet id; unique, so an Initiative is never processed twice. */
    @Column(name = "initiative_id", length = 36, unique = true)
    public String initiativeId;

    /** Name of the LeanIX Initiative the review was created for; filled in later for older rows. */
    @Column(name = "initiative_name", length = 255)
    public String initiativeName;

    /** Value of the ARBPhase field set on the review when it was created. */
    @Column(name = "arb_phase", length = 30)
    public String arbPhase;

    /** Name of the tag added to the review when it was created. */
    @Column(name = "arb_tag", length = 60)
    public String arbTag;

    /** The itManager attribute of the Initiative, as "Last, First", or null if it has none. */
    @Column(name = "it_manager", length = 255)
    public String itManager;

    /** Email address of the manager: the itManagerEmail attribute of the Initiative, or the address of the LeanIX user named in itManager. */
    @Column(name = "it_manager_email", length = 255)
    public String itManagerEmail;

    /** Enterprise Architects subscribed to the review (email addresses separated by ';'), taken from the review team of the manager. */
    @Column(name = "enterprise_architect", length = 500)
    public String enterpriseArchitect;

    /** Solution Architects subscribed to the review (email addresses separated by ';'), taken from the review team of the manager. */
    @Column(name = "solution_architect", length = 500)
    public String solutionArchitect;

    /** Outcome of subscribing the Enterprise and Solution Architects: Assigned, No team for manager, or what failed. */
    @Column(name = "team_status", length = 255)
    public String teamStatus;

    /** Outcome of subscribing the manager to the review: Assigned, No manager, Manager not found in LeanIX, or what failed. */
    @Column(name = "manager_status", length = 255)
    public String managerStatus;

    /** LeanIX ArchitectureReview fact sheet id created in response. */
    @Column(name = "arb_fs_id", length = 36)
    public String arbFsId;

    /**
     * Tells whether an Initiative already has a review.
     *
     * @param initiativeId  The LeanIX Initiative fact sheet id.
     * @return               True if a record exists for the Initiative.
     */
    public static boolean existsByInitiativeId(String initiativeId) {
        return find("initiativeId", initiativeId).count() > 0;
    }
}
